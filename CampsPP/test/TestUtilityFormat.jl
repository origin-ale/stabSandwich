# Phase 7 step 1: format pins for the output writers used by the kept scripts
# (Comptime_prob_tm.jl, TransferredMag_varparams.jl, switch_optimization.jl,
# Comptime_ratios.jl, Comptime_3_squarecirc.jl; Randrot_complexity.jl writes its own file).
#
# The gnuplot scripts in plotting/ read these layouts, and T11 cannot catch a writer bug
# (old and new runs share the writers). Each test writes a small file the way a script does
# and compares it byte for byte with the expected lines below.
#
# The expected lines are written by hand from the writer code and checked against a real
# output file (output/campspp_switch_prob_tm.txt, Phase 0); they are not generated by the
# writers. Inputs are chosen so every mean, error and quartile is exact in Float64, so the
# expected strings can be checked by hand. The numerical checks with inexact values
# (mean and error on generic data) compare against hand formulas instead.
#
# Block labels (post-port item 9, CONVENTIONS.md §2 "Output labels"): the writers take a
# label pair. Count mode, `"n" => n`, gives `# n = <n>, μ = <μ>` with n an integer (the
# scripts); `"p" => p` gives `# p = <p>, μ = <μ>` (the T11 replay of the Phase 0 runs). The
# per-writer testsets below use the p form; "count-mode labels" pins the n form.
#
# Change a layout only on purpose: update the expected lines here and the plot scripts that
# read the file together.
#
# Header order: since Phase 7 the scripts pass `param_header(params)` (a vector of
# `"name" => "value"` string pairs, scripts/ScriptSetup.jl), written in the given order; that
# order is pinned below. A `Dict` is still accepted and written in its iteration order, which
# is only pinned as such (it is not stable across key sets or Julia versions).

"File contents made of `lines`, each terminated by a newline."
golden(lines) = join(lines, "\n") * "\n"

"""
Compare file `path` with `lines`; on a mismatch, print the first differing line (repr'd,
so trailing spaces and tabs show) before the test fails.
"""
function matches_golden(path, lines)
  got = read(path, String)
  want = golden(lines)
  got == want && return true
  g, w = split(got, '\n'), split(want, '\n')
  i = findfirst(k -> k > length(g) || k > length(w) || g[k] != w[k], 1:max(length(g), length(w)))
  println("Format mismatch in $(basename(path)) at line $i:\n  got:  ",
    i <= length(g) ? repr(g[i]) : "<EOF>", "\n  want: ", i <= length(w) ? repr(w[i]) : "<EOF>")
  return false
end

"Data lines of `path` as vectors of space-separated fields (comments and blanks dropped)."
fields(path) = [split(l, ' ') for l in eachline(path) if !isempty(l) && !startswith(l, '#')]

# Header written by `initialize_output(path, "obs", ["N" => "46"])` (one parameter).
const HEADER = ["# N=46  ", "# Cycle obs", "", ""]

@testset "Utility.jl output formats" begin
  mktempdir() do dir
    file(name) = joinpath(dir, name)

    @testset "initialize_output" begin
      path = file("init.txt")
      write(path, "stale contents\n")
      initialize_output(path, "obs", ["N" => "46"])
      @test matches_golden(path, HEADER)              # overwrites, does not append

      initialize_output(path, "[layer, value]", Dict())
      @test matches_golden(path, ["#  ", "# Cycle [layer, value]", "", ""])

      params = Dict("N" => 46, "μ" => 0.6, "magic_mode" => "xy", "thl" => 1e-10)
      initialize_output(path, "obs", params)
      want = "# " * join(["$k=$v" for (k, v) in params], " ") * "  "
      @test readline(path) == want                    # key=value, Dict iteration order
      @test Set(split(strip(readline(path)[3:end]), ' ')) ==
            Set(["N=46", "μ=0.6", "magic_mode=xy", "thl=1.0e-10"])

      # String pairs as `param_header` gives them (what the scripts pass): the given order,
      # not sorted (`samples=` is what plotting/hist_setup.plt greps for)
      initialize_output(path, "obs", ["N" => "46", "magic_probs" => "0.0,0.01", "samples" => "25",
                                      "μ" => "0.6", "methods" => "campspp,pp", "Ns" => "4:2:8"])
      @test matches_golden(path, ["# N=46 magic_probs=0.0,0.01 samples=25 μ=0.6 methods=campspp,pp Ns=4:2:8  ",
                                  "# Cycle obs", "", ""])
      initialize_output(path, "obs", ["z" => "1", "a" => "2", "m" => "3"])
      @test readline(path) == "# z=1 a=2 m=3  "
      initialize_output(path, "obs", [:N => 46, :t => 23])        # Symbol keys, numbers
      @test readline(path) == "# N=46 t=23  "
      initialize_output(path, "obs", Pair{String, String}[])
      @test matches_golden(path, ["#  ", "# Cycle obs", "", ""])

      # NamedTuple: field order, each value as `string` gives it
      initialize_output(path, "evs", (N = 46, μ = 0.6, method = :campspp, thl = 1e-10, a = "x"))
      @test matches_golden(path, ["# N=46 μ=0.6 method=campspp thl=1.0e-10 a=x  ", "# Cycle evs", "", ""])
      initialize_output(path, "evs", NamedTuple())
      @test readline(path) == "#  "

      # An unsupported `params` throws before the file is opened, so it is not truncated
      write(path, "keep\n")
      @test_throws MethodError initialize_output(path, "obs", 46)
      @test_throws MethodError initialize_output(path, "obs", ("N", 46))
      @test read(path, String) == "keep\n"
    end

    @testset "append_datapoint (src dynamics outputs)" begin
      path = file("dyn.txt")
      initialize_output(path, "obs", ["N" => "46"])
      append_datapoint(path, 0, 1.0)
      append_datapoint(path, 1, -0.25)
      append_datapoint(path, 2, 1e-5)
      @test matches_golden(path, [HEADER; "0\t1.0"; "1\t-0.25"; "2\t1.0e-5"])
    end

    @testset "quantiles" begin
      @test quantiles([1, 2, 3, 4]) === (1.75, 2.5, 3.25)     # Hyndman–Fan type 7
      @test quantiles([4, 1, 3, 2]) === (1.75, 2.5, 3.25)     # order of input irrelevant
      @test quantiles([0.0, 0.0, 0.0, 6.0]) === (0.0, 0.0, 1.5)
      @test quantiles([1, 5]) === (2.0, 3.0, 4.0)
      @test quantiles([2.5]) === (2.5, 2.5, 2.5)
      q = quantiles(Float64[])
      @test q isa NTuple{3, Float64} && all(isnan, q)
      @test quantiles(Int[]) isa NTuple{3, Float64}
    end

    @testset "stack_samples" begin
      evs = stack_samples([[1, 2, 3], [4]])
      @test evs isa Matrix{Union{Missing, Int}}
      @test size(evs) == (3, 2)                          # layers × samples
      @test isequal(evs, [1 4; 2 missing; 3 missing])    # short samples padded at the end

      lead = Union{Missing, Float64}[missing, 0.5]
      evs = stack_samples([lead, [1.0, 2.0, 3.0]])
      @test size(evs) == (3, 2)
      @test isequal(evs[:, 1], [missing, 0.5, missing])
      @test isequal(evs[:, 2], [1.0, 2.0, 3.0])

      @test isequal(stack_samples([[7.0]]), reshape(Union{Missing, Float64}[7.0], 1, 1))

      # The element type is promoted over all samples, not taken from the first one (an
      # Int first sample used to turn a later 2.0 into 2 and throw InexactError on 0.5)
      evs = stack_samples([[1, 2], [0.5]])
      @test evs isa Matrix{Union{Missing, Float64}}
      @test isequal(evs, [1.0 0.5; 2.0 missing])
      @test evs[1, 1] === 1.0 && evs[2, 1] === 2.0 && evs[1, 2] === 0.5
      evs = stack_samples([[3], [2.0, 1.5]])
      @test evs isa Matrix{Union{Missing, Float64}} && isequal(evs, [3.0 2.0; missing 1.5])
      evs = stack_samples([[0.5], [1, 2]])                 # order of the samples irrelevant
      @test evs isa Matrix{Union{Missing, Float64}} && isequal(evs, [0.5 1.0; missing 2.0])
      evs = stack_samples([Missing[missing], [1.0]])      # an all-missing sample
      @test evs isa Matrix{Union{Missing, Float64}} && isequal(evs, reshape([missing, 1.0], 1, 2))
      @test stack_samples([[1], [2, 3]]) isa Matrix{Union{Missing, Int}}   # same type kept
      # As written: an Int-and-Float stack prints floats in every column
      path = file("promoted.txt")
      initialize_output(path, "obs", ["N" => "46"])
      save_full_samples(path, 0.6, "p" => 0.01, stack_samples([[1, 2], [0.5]]))
      @test matches_golden(path, [HEADER; "# p = 0.01, μ = 0.6";
        "# sample 1"; "0\t1.0"; "1\t2.0"; ""; "# sample 2"; "0\t0.5"; ""; ""])
    end

    @testset "save_full_samples" begin
      path = file("full.txt")
      initialize_output(path, "obs", ["N" => "46"])
      s1 = [1.0, 0.5, 0.25]
      s2 = [0.75, -0.5]                                  # stopped early
      s3 = Union{Missing, Float64}[missing, 3.0, 4.0]    # starts mid-circuit
      save_full_samples(path, 0.6, "p" => 0.01, stack_samples([s1, s2, s3]))
      save_full_samples(path, 0.6, "p" => 0.02, stack_samples([[2.0]]))
      @test matches_golden(path, [HEADER;
        "# p = 0.01, μ = 0.6";
        "# sample 1"; "0\t1.0"; "1\t0.5"; "2\t0.25"; "";
        "# sample 2"; "0\t0.75"; "1\t-0.5"; "";
        "# sample 3"; "1\t3.0"; "2\t4.0"; "";            # missing rows skipped, layer kept
        "";
        "# p = 0.02, μ = 0.6";
        "# sample 1"; "0\t2.0"; "";
        ""])
    end

    @testset "save_per_sample" begin
      path = file("persample.txt")
      initialize_output(path, "obs", ["N" => "46"])
      save_per_sample(path, 0.6, "p" => 0.0, [1.5, 2.25], [0.0, 0.125])       # times, GC times
